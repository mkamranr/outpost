"""Apply a sandbox result to GitLab. This is the only place the platform writes code to GitLab."""
from __future__ import annotations

import re
from typing import Any, Callable

from .changes import ChangeRejected, ci_contents, to_actions
from .common import OutputContext, failure_message, sanitize

Handler = Callable[[OutputContext], str]
HANDLERS: dict[str, Handler] = {}


def handler(name: str) -> Callable[[Handler], Handler]:
    def wrap(fn: Handler) -> Handler:
        HANDLERS[name] = fn
        return fn
    return wrap


def apply(ctx: OutputContext) -> str:
    """Run the agent's output handler; returns a short outcome string stored on the task."""
    try:
        return HANDLERS[ctx.agent.output](ctx)
    except ChangeRejected as exc:
        ctx.notify(failure_message(ctx, f"I produced a change but it was rejected by platform policy: {exc}"))
        return f"rejected: {exc}"


# -- shared steps ------------------------------------------------------------------

def _actions(ctx: OutputContext) -> list[dict[str, Any]]:
    return to_actions(ctx.result.get("changes") or [], ctx.project.protected_paths, ctx.agent.allow_ci_changes)


def _lint_ci(ctx: OutputContext, actions: list[dict[str, Any]], ref: str) -> None:
    for path, content in ci_contents(actions).items():
        if path != ".gitlab-ci.yml":
            continue  # included fragments are validated through the MR pipeline itself
        lint = ctx.gl.ci_lint_content(ctx.target["project_id"], content, ref=ref)
        if not lint.get("valid"):
            errors = "; ".join(lint.get("errors") or ["invalid"])
            raise ChangeRejected(f".gitlab-ci.yml failed CI lint: {errors}")


def _commit_message(ctx: OutputContext, title: str) -> str:
    return f"{title}\n\nGenerated by the {ctx.agent.name} agent (task {ctx.task.id}).\nCo-authored-by: agent <{ctx.settings.bot_username}@agent.local>"


def _mr_description(ctx: OutputContext, intro: str) -> str:
    parts = [intro, "### Summary", sanitize(ctx.result.get("summary") or "_No summary provided._")]
    attempts = ctx.attempts_markdown()
    if attempts:
        parts += ["### Attempts", attempts]
    parts.append(f"> ⚠️ Generated by the `{ctx.agent.name}` agent. Review it like any other contribution; "
                 "the MR pipeline is the final check.")
    return "\n\n".join(parts)


def _branch_head_matches(ctx: OutputContext, branch: str, expected_sha: str) -> bool:
    head = ctx.gl.branch(ctx.target["project_id"], branch)
    return bool(head) and head["commit"]["id"] == expected_sha


def _open_mr(ctx: OutputContext, *, actions: list[dict[str, Any]], branch: str, start_sha: str, target_branch: str,
             title: str, intro: str, labels: str = "agent::generated") -> dict[str, Any]:
    pid = ctx.target["project_id"]
    ctx.gl.create_commit(pid, branch, _commit_message(ctx, title), actions, start_sha=start_sha)
    return ctx.gl.create_merge_request(
        pid,
        source_branch=branch,
        target_branch=target_branch,
        title=f"Draft: {title}",
        description=_mr_description(ctx, intro),
        remove_source_branch=True,
        labels=labels,
    )


# -- handlers -----------------------------------------------------------------------

@handler("pipeline_fix")
def pipeline_fix(ctx: OutputContext) -> str:
    r, t = ctx.result, ctx.target
    pid, pipeline_id, ref, sha = t["project_id"], t["pipeline_id"], t["ref"], t["sha"]
    summary = sanitize(r.get("summary") or "")

    if r.get("classification") == "flaky":
        retried = []
        for job_id in t.get("failed_job_ids") or []:
            try:
                ctx.gl.retry_job(pid, job_id)
                retried.append(str(job_id))
            except Exception:  # noqa: BLE001 - a job may already have been retried by a human
                pass
        ctx.notify(f"Pipeline #{pipeline_id} failed for reasons that look **flaky or infrastructure-related**, "
                   f"not a code or CI problem. Retried job(s): {', '.join(retried) or 'none'}.\n\n{summary}")
        return f"retried {len(retried)} job(s)"

    if r.get("status") != "success" or not r.get("changes"):
        ctx.notify(failure_message(ctx, f"I could not fix pipeline #{pipeline_id} automatically."))
        return "no fix"

    actions = _actions(ctx)
    _lint_ci(ctx, actions, ref)
    title = sanitize(r.get("title") or f"Fix pipeline #{pipeline_id} on {ref}", 200).splitlines()[0]

    if ref.startswith("agent/"):
        # Iterating on our own branch: add a commit, the MR already exists.
        if not _branch_head_matches(ctx, ref, sha):
            ctx.notify(f"`{ref}` moved while I was working, so I did not push my fix for pipeline #{pipeline_id}.")
            return "stale branch"
        ctx.gl.create_commit(pid, ref, _commit_message(ctx, title), actions)
        ctx.produced = {"ok": True, "summary": summary,
                        "mr_iid": t.get("iid") if t.get("noteable_type") == "merge_request" else None}
        ctx.notify(f"Pushed another fix attempt to `{ref}`.\n\n{summary}\n\n{ctx.attempts_markdown()}")
        return f"pushed to {ref}"

    mr = _open_mr(
        ctx, actions=actions, branch=ctx.branch_name(f"pipeline-{pipeline_id}"), start_sha=sha, target_branch=ref,
        title=title, intro=f"Fixes the failure in pipeline #{pipeline_id} on `{ref}` (commit {sha[:8]}). "
                           f"Failure classified as **{r.get('classification') or 'code'}**.",
    )
    ctx.produced = {"ok": True, "mr_iid": mr["iid"], "summary": summary}
    ctx.notify(f"Pipeline #{pipeline_id} failed. I opened !{mr['iid']} with a proposed fix.\n\n{summary}")
    return mr.get("web_url", f"!{mr['iid']}")


@handler("merge_request")
def merge_request(ctx: OutputContext) -> str:
    r, t = ctx.result, ctx.target
    if r.get("status") != "success" or not r.get("changes"):
        ctx.notify(failure_message(ctx, "I could not complete the implementation."))
        return "no change"
    actions = _actions(ctx)
    repo = ctx.bundle.get("repo", {})
    _lint_ci(ctx, actions, repo["ref"])
    iid = t["iid"]
    title = sanitize(r.get("title") or f"Implement #{iid}", 200).splitlines()[0]
    mr = _open_mr(
        ctx, actions=actions, branch=ctx.branch_name(f"issue-{iid}"), start_sha=repo["sha"], target_branch=repo["ref"],
        title=title, intro=f"Closes #{iid}",
    )
    ctx.produced = {"ok": True, "mr_iid": mr["iid"], "summary": sanitize(r.get("summary") or "", 3000)}
    ctx.notify(f"I opened !{mr['iid']} implementing this issue.\n\n{sanitize(r.get('summary') or '')}")
    return mr.get("web_url", f"!{mr['iid']}")


@handler("mr_commit")
def mr_commit(ctx: OutputContext) -> str:
    r, t = ctx.result, ctx.target
    if r.get("status") != "success" or not r.get("changes"):
        ctx.notify(failure_message(ctx, "I could not make that change."))
        return "no change"
    pid = t["project_id"]
    mr = ctx.gl.merge_request(pid, t["iid"])
    if mr.get("source_project_id") != mr.get("project_id"):
        ctx.notify("This merge request comes from a fork; I can only change branches in this project.")
        return "fork"
    actions = _actions(ctx)
    source, expected = mr["source_branch"], ctx.bundle.get("repo", {}).get("sha")
    _lint_ci(ctx, actions, source)
    title = sanitize(r.get("title") or f"Address review on !{t['iid']}", 200).splitlines()[0]

    if source.startswith("agent/") or ctx.project.allow_push_to_mr_branch:
        if not _branch_head_matches(ctx, source, expected):
            ctx.notify(f"`{source}` changed while I was working. Ask me again to apply the change on the new head.")
            return "stale branch"
        ctx.gl.create_commit(pid, source, _commit_message(ctx, title), actions)
        ctx.produced = {"ok": True, "mr_iid": t["iid"], "summary": sanitize(r.get("summary") or "", 3000)}
        ctx.notify(f"Pushed a commit to `{source}`.\n\n{sanitize(r.get('summary') or '')}\n\n{ctx.attempts_markdown()}")
        return f"pushed to {source}"

    # Human-owned branch: never push to it directly; stack a follow-up MR on top instead.
    new_mr = _open_mr(
        ctx, actions=actions, branch=ctx.branch_name(f"mr-{t['iid']}"), start_sha=expected, target_branch=source,
        title=title, intro=f"Follow-up for !{t['iid']}, requested in review.",
    )
    ctx.produced = {"ok": True, "mr_iid": new_mr["iid"], "summary": sanitize(r.get("summary") or "", 3000)}
    ctx.notify(f"I opened !{new_mr['iid']} targeting `{source}` with the change.\n\n{sanitize(r.get('summary') or '')}")
    return new_mr.get("web_url", f"!{new_mr['iid']}")


@handler("note")
def note(ctx: OutputContext) -> str:
    r = ctx.result
    if r.get("status") != "success" or not r.get("body"):
        ctx.notify(failure_message(ctx, "I could not complete this request."))
        return "failed"
    body = r["body"]
    if ctx.agent.note_suffix:
        body += "\n\n" + ctx.agent.note_suffix.replace("{mention}", ctx.settings.mention)
    if ctx.agent.note_marker:
        body = f"{ctx.agent.note_marker}\n{body}"
    # The marker must survive sanitize(), which only touches quick actions and mass mentions.
    note = ctx.notify(body)
    ctx.produced = {"ok": True, "summary": sanitize(r["body"], 3000),
                    "note_id": note.get("id") if isinstance(note, dict) else None}
    return "commented"


@handler("review")
def review(ctx: OutputContext) -> str:
    r, t = ctx.result, ctx.target
    if r.get("status") != "success":
        ctx.notify(failure_message(ctx, "I could not complete the review."))
        return "failed"
    pid, iid = t["project_id"], t["iid"]
    refs = ctx.gl.merge_request(pid, iid).get("diff_refs") or {}
    posted, unplaced = 0, []
    for c in (r.get("comments") or [])[:25]:
        body = sanitize(c.get("body"), 4000) + ctx.footer()
        try:
            line = int(c["line"])
            position = {
                "position_type": "text",
                "base_sha": refs["base_sha"],
                "start_sha": refs["start_sha"],
                "head_sha": refs["head_sha"],
                "new_path": c["path"],
                "old_path": c.get("old_path") or c["path"],
                "new_line": line,
            }
            ctx.remember(ctx.gl.create_mr_discussion(pid, iid, body, position))
            posted += 1
        except Exception:  # noqa: BLE001 - lines outside the diff cannot be anchored; keep them in the summary
            unplaced.append(f"- `{c.get('path')}:{c.get('line')}` — {sanitize(c.get('body'), 1000)}")
    summary = sanitize(r.get("summary") or "Review complete.")
    if unplaced:
        summary += "\n\n**Comments not attached to diff lines:**\n" + "\n".join(unplaced)
    ctx.produced = {"ok": True, "summary": summary[:3000], "comments": posted}
    ctx.notify(f"**Review:** {posted} inline comment(s).\n\n{summary}")
    return f"{posted} comments"


@handler("chat")
def chat(ctx: OutputContext) -> str:
    r = ctx.result
    if r.get("status") != "success" or not r.get("body"):
        ctx.notify(failure_message(ctx, "I could not answer that."))
        return "failed"
    body = r["body"]
    handoff = r.get("handoff")
    routed = ""
    if isinstance(handoff, dict) and handoff.get("target") and ctx.handoff:
        routed = ctx.handoff(str(handoff["target"]), str(handoff.get("instruction") or ""))
        if routed:
            body += "\n\n" + routed
    note = ctx.notify(body)
    ctx.produced = {"ok": True, "summary": sanitize(r["body"], 3000),
                    "note_id": note.get("id") if isinstance(note, dict) else None}
    return f"replied; handoff to {handoff['target']}" if routed else "replied"


# -- MR descriptions --------------------------------------------------------------------

DESCRIPTION_START = "<!-- outpost:description -->"
DESCRIPTION_END = "<!-- /outpost:description -->"
_HTML_COMMENT = re.compile(r"<!--.*?-->", re.DOTALL)
_GENERATED_BLOCK = re.compile(re.escape(DESCRIPTION_START) + r".*?" + re.escape(DESCRIPTION_END), re.DOTALL)


def description_is_empty(description: str) -> bool:
    """True for blank descriptions, untouched MR templates (comments only) and our own generated block."""
    text = _HTML_COMMENT.sub("", _GENERATED_BLOCK.sub("", description or ""))
    return len(re.sub(r"\s+", " ", text).strip()) < 40


def merge_description(current: str, generated: str) -> str:
    """Put the generated text in its marker block: replace an earlier block, otherwise append. Human text stays."""
    block = f"{DESCRIPTION_START}\n{generated.strip()}\n{DESCRIPTION_END}"
    current = current or ""
    if _GENERATED_BLOCK.search(current):
        return _GENERATED_BLOCK.sub(lambda _: block, current, count=1)
    if not current.strip() or not _HTML_COMMENT.sub("", current).strip():
        return block  # empty, or only an MR template's comments
    return f"{current.rstrip()}\n\n{block}"


@handler("mr_description")
def mr_description(ctx: OutputContext) -> str:
    r, t = ctx.result, ctx.target
    if r.get("status") != "success" or not r.get("body"):
        if ctx.task.command:  # stay quiet on automatic runs
            ctx.notify(failure_message(ctx, "I could not write a description."))
        return "failed"
    pid, iid = t["project_id"], t["iid"]
    # The model must not be able to close our block early and write outside it.
    body = sanitize(r["body"], 12000).replace(DESCRIPTION_START, "").replace(DESCRIPTION_END, "")
    body += f"\n\n<sub>🤖 Written by the `{ctx.agent.name}` agent from the diff; edit freely.</sub>"
    current = ctx.gl.merge_request(pid, iid).get("description") or ""
    ctx.gl.update_merge_request(pid, iid, description=merge_description(current, body))
    ctx.produced = {"ok": True, "summary": sanitize(r["body"], 3000)}
    if ctx.task.command:
        ctx.notify("Updated the merge request description.")
    return "description updated"


# -- issue triage -----------------------------------------------------------------------

@handler("triage")
def triage(ctx: OutputContext) -> str:
    r, t = ctx.result, ctx.target
    if r.get("status") != "success":
        if ctx.task.command:
            ctx.notify(failure_message(ctx, "I could not triage this issue."))
        return "failed"
    pid, iid = t["project_id"], t["iid"]
    data = r.get("triage") or {}
    issue = ctx.gl.issue(pid, iid)
    existing = {l["name"] for l in ctx.gl.labels(pid)}
    current = set(issue.get("labels") or [])
    # Only real labels, never agent trigger labels: a triage must not start other agents.
    labels = [l for l in dict.fromkeys(str(x) for x in data.get("labels") or [])
              if l in existing and l not in current and not l.startswith("agent::")][:5]
    duplicates = []
    for d in (data.get("duplicates") or [])[:5]:
        try:
            other = int(d.get("iid"))
        except (TypeError, ValueError, AttributeError):
            continue
        if other == iid:
            continue
        try:
            found = ctx.gl.issue(pid, other)
        except Exception:  # noqa: BLE001 - the model named an issue that does not exist
            continue
        duplicates.append(f"- #{other} {sanitize(found.get('title'), 200)}: {sanitize(str(d.get('reason') or ''), 300)}")
    questions = [f"- {sanitize(str(q), 400)}" for q in (data.get("missing_info") or [])[:5] if str(q).strip()]

    parts = [f"**Triage:** {sanitize(r.get('summary') or r.get('body') or '', 1000)}"]
    if labels:
        applied = ctx.project.triage.apply_labels
        if applied:
            ctx.gl.update_issue(pid, iid, add_labels=",".join(labels))
        names = " ".join(f'~"{l}"' for l in labels)
        parts.append(f"**{'Labels added' if applied else 'Suggested labels'}:** {names}")
    if duplicates:
        parts.append("**Possible duplicates:**\n" + "\n".join(duplicates))
    if questions:
        parts.append("**To help someone pick this up, could you add:**\n" + "\n".join(questions))
    note = ctx.notify("\n\n".join(parts))
    ctx.produced = {"ok": True, "summary": "\n\n".join(parts)[:3000],
                    "note_id": note.get("id") if isinstance(note, dict) else None}
    return f"triaged: {len(labels)} label(s), {len(duplicates)} duplicate(s), {len(questions)} question(s)"


# -- security fixes ---------------------------------------------------------------------

SECURITY_LABEL = "agent::security-fix"


def _findings_table(ctx: OutputContext) -> str:
    vulns = (ctx.bundle.get("context") or {}).get("vulnerabilities") or {}
    findings = vulns.get("findings") or [] if isinstance(vulns, dict) else []
    if not findings:
        return ""
    rows = ["| Severity | Finding | Location | Id |", "| --- | --- | --- | --- |"]
    for f in findings:
        where = f.get("file") or f.get("package") or "?"
        if f.get("line"):
            where += f":{f['line']}"
        ident = ", ".join((f.get("identifiers") or [])[:2]) or str(f.get("id") or "")[:12]
        rows.append(f"| {f['severity']} | {sanitize(str(f.get('name') or '?'), 120).replace('|', '/')} | "
                    f"`{where}` | {sanitize(ident, 80).replace('|', '/')} |")
    return "\n".join(rows)


@handler("security_fix")
def security_fix(ctx: OutputContext) -> str:
    """On an MR: like mr_commit (commit on agent branches, else a follow-up MR). After a pipeline: a new MR."""
    t, r = ctx.target, ctx.result
    if t.get("kind") != "pipeline" and t.get("noteable_type") == "merge_request":
        return mr_commit(ctx)
    pipeline_id, ref, sha = t["pipeline_id"], t["ref"], t["sha"]
    if r.get("status") != "success" or not r.get("changes"):
        ctx.notify(failure_message(ctx, f"I could not fix the security findings of pipeline #{pipeline_id}."))
        return "no fix"
    actions = _actions(ctx)
    _lint_ci(ctx, actions, ref)
    title = sanitize(r.get("title") or f"Fix security findings from pipeline #{pipeline_id}", 200).splitlines()[0]
    table = _findings_table(ctx)
    intro = (f"Addresses security scanner findings from pipeline #{pipeline_id} on `{ref}` (commit {sha[:8]})."
             + (f"\n\n**Findings in scope**\n\n{table}" if table else "")
             + "\n\nThe summary below says which ones this change fixes; check that each fix removes the root cause.")
    mr = _open_mr(ctx, actions=actions, branch=ctx.branch_name(f"vuln-{pipeline_id}"), start_sha=sha,
                  target_branch=ref, title=title, intro=intro, labels=f"agent::generated,{SECURITY_LABEL}")
    ctx.produced = {"ok": True, "mr_iid": mr["iid"], "summary": sanitize(r.get("summary") or "", 3000)}
    ctx.notify(f"Pipeline #{pipeline_id} reported security findings. I opened !{mr['iid']} with proposed fixes.")
    return mr.get("web_url", f"!{mr['iid']}")
