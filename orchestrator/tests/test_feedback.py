"""Feedback: links from tasks to what they created, outcome events, reaction polling, dashboard and metrics."""
import base64

from fastapi.testclient import TestClient

from app.events import parse
from app.main import create_app
from app.tasks import MR_CLOSED, MR_MERGED, PIPELINE_GREEN, THUMBS_DOWN, THUMBS_UP
from tests.test_platform_flow import dispatch_and_get_ticket, wire_pipeline_project

MR_HEADERS = {"X-Gitlab-Token": "hook-secret", "X-Gitlab-Event": "Merge Request Hook"}
PIPE_HEADERS = {"X-Gitlab-Token": "hook-secret", "X-Gitlab-Event": "Pipeline Hook"}


def finished_fix_task(platform, fake, client):
    """Run the pipeline fixer end to end: it opens MR !9 and comments on the commit."""
    wire_pipeline_project(fake)
    task_id, ticket = dispatch_and_get_ticket(platform, fake, client)
    result = {"status": "success", "classification": "code", "title": "Fix add()", "summary": "fixed",
              "changes": [{"action": "update", "path": "src/calc.py",
                           "content_b64": base64.b64encode(b"x = 1\n").decode()}]}
    client.post(f"/api/tasks/{task_id}/result", json=result, headers={"Authorization": f"Bearer {ticket}"})
    platform.run_once()
    return platform.store.get(task_id)


def mr_event(action, iid=9, branch="feature/x", user="alice"):
    return {"object_kind": "merge_request", "user": {"id": 5, "username": user},
            "project": {"id": 42, "path_with_namespace": "group/app"},
            "object_attributes": {"iid": iid, "action": action, "source_branch": branch}}


def kinds(platform, task_id):
    return sorted((f.kind, f.actor) for f in platform.store.feedback_for([task_id]))


def test_merged_agent_mr_is_recorded_once(platform, fake):
    client = TestClient(create_app(platform))
    task = finished_fix_task(platform, fake, client)
    client.post("/webhook", json=mr_event("merge"), headers=MR_HEADERS)
    client.post("/webhook", json=mr_event("merge"), headers=MR_HEADERS)  # redelivery
    assert kinds(platform, task.id) == [(MR_MERGED, "")]


def test_unknown_mr_is_ignored_and_branch_name_is_a_fallback(platform, fake):
    client = TestClient(create_app(platform))
    task = finished_fix_task(platform, fake, client)
    client.post("/webhook", json=mr_event("close", iid=123), headers=MR_HEADERS)
    assert kinds(platform, task.id) == []
    # An MR the link table does not know, on the task's branch (e.g. recreated by hand): found by branch name.
    branch = f"agent/pipeline-fixer-pipeline-501-{task.id[:6]}"
    client.post("/webhook", json=mr_event("close", iid=124, branch=branch), headers=MR_HEADERS)
    assert kinds(platform, task.id) == [(MR_CLOSED, "")]


def test_green_pipeline_on_agent_branch_names_the_task(platform, fake):
    client = TestClient(create_app(platform))
    task = finished_fix_task(platform, fake, client)
    payload = {"object_kind": "pipeline", "user": {"id": 1, "username": "agent-bot"},
               "project": {"id": 42, "path_with_namespace": "group/app"},
               "object_attributes": {"id": 777, "status": "success", "ref": "agent/pipeline-fixer-pipeline-501-zzzzzz",
                                     "sha": "c" * 40},
               "commit": {"message": f"Fix add()\n\nGenerated by the pipeline-fixer agent (task {task.id})."}}
    client.post("/webhook", json=payload, headers=PIPE_HEADERS)
    assert kinds(platform, task.id) == [(PIPELINE_GREEN, "")]


def test_poller_syncs_reactions_and_ignores_the_bot(platform, fake):
    client = TestClient(create_app(platform))
    task = finished_fix_task(platform, fake, client)
    awards = [{"name": "thumbsup", "user": {"username": "alice"}},
              {"name": "thumbsdown", "user": {"username": "bob"}},
              {"name": "thumbsup", "user": {"username": "agent-bot"}},
              {"name": "eyes", "user": {"username": "carol"}}]
    fake.on("GET", "/projects/42/merge_requests/9/award_emoji", lambda req, m: awards)
    assert platform.reactions.poll() == 1
    assert kinds(platform, task.id) == [(THUMBS_DOWN, "bob"), (THUMBS_UP, "alice")]
    platform.reactions.poll()  # polling again does not double count
    assert kinds(platform, task.id) == [(THUMBS_DOWN, "bob"), (THUMBS_UP, "alice")]
    awards.pop(1)  # bob withdrew the 👎
    platform.reactions.poll()
    assert kinds(platform, task.id) == [(THUMBS_UP, "alice")]


def test_notes_on_issue_or_mr_are_linked(platform, fake):
    from app.feedback import links_for
    from app.outputs.common import OutputContext

    task = platform.store.create(agent="planner", project_id=42, project_path="group/app", dedupe_key="k",
                                 subject_key="s", target={"kind": "note", "project_id": 42, "noteable_type": "issue",
                                                          "iid": 3, "note_id": 1})
    fake.on("POST", "/projects/42/issues/3/notes", {"id": 555})
    ctx = OutputContext(fake.client(), task, platform.registry.get("planner"), {}, platform.projects.defaults,
                        platform.settings)
    ctx.notify("hello")
    assert links_for(ctx) == [{"kind": "note", "ref_id": 555, "noteable_type": "issue", "noteable_iid": 3}]
    # A commit pushed onto the subject MR itself does not make that MR the task's work.
    task2 = platform.store.create(agent="mr-assist", project_id=42, project_path="group/app", dedupe_key="k2",
                                  subject_key="s2", target={"kind": "note", "project_id": 42,
                                                            "noteable_type": "merge_request", "iid": 7})
    ctx2 = OutputContext(fake.client(), task2, platform.registry.get("mr-assist"), {}, platform.projects.defaults,
                         platform.settings, produced={"mr_iid": 7})
    assert links_for(ctx2) == []


def test_admin_views_need_the_token(platform, fake):
    client = TestClient(create_app(platform))
    task = finished_fix_task(platform, fake, client)
    client.post("/webhook", json=mr_event("merge"), headers=MR_HEADERS)
    for path in ("/admin", "/metrics", "/api/tasks"):
        resp = client.get(path)
        assert resp.status_code == 401, path
    assert client.get("/admin").headers["www-authenticate"].startswith("Basic")
    assert client.get("/metrics", headers={"Authorization": "Bearer wrong"}).status_code == 401

    metrics = client.get("/metrics", headers={"Authorization": "Bearer admin"})
    assert metrics.status_code == 200
    assert 'outpost_tasks{agent="pipeline-fixer",status="done"} 1' in metrics.text
    assert 'outpost_feedback{agent="pipeline-fixer",kind="mr_merged"} 1' in metrics.text
    assert 'outpost_queue_depth{lane="sandbox"} 0' in metrics.text

    basic = base64.b64encode(b"ops:admin").decode()
    page = client.get("/admin?days=7", headers={"Authorization": f"Basic {basic}"})
    assert page.status_code == 200
    assert "pipeline-fixer" in page.text and "100%" in page.text  # one merged of one decided
    assert client.get("/api/tasks", headers={"X-Admin-Token": "admin"}).json()[0]["id"] == task.id


def test_pipeline_event_keeps_commit_message():
    event = parse("Pipeline Hook", {"object_kind": "pipeline", "project": {"id": 1}, "object_attributes": {"id": 2},
                                    "commit": {"message": "msg"}})
    assert event.commit_message == "msg"
    assert "commit_message" not in event.target()


def test_llm_usage_is_stored_and_shown(platform, fake):
    client = TestClient(create_app(platform))
    wire_pipeline_project(fake)
    task_id, ticket = dispatch_and_get_ticket(platform, fake, client)
    result = {"status": "success", "classification": "flaky", "summary": "network blip",
              "usage": {"prompt_tokens": 41000, "completion_tokens": 900, "calls": 5}}
    client.post(f"/api/tasks/{task_id}/result", json=result, headers={"Authorization": f"Bearer {ticket}"})
    platform.run_once()
    task = platform.store.get(task_id)
    assert (task.prompt_tokens, task.completion_tokens, task.llm_calls) == (41000, 900, 5)

    metrics = client.get("/metrics", headers={"Authorization": "Bearer admin"}).text
    assert 'outpost_llm_tokens{agent="pipeline-fixer",type="prompt"} 41000' in metrics
    assert 'outpost_llm_tokens{agent="pipeline-fixer",type="completion"} 900' in metrics
    assert 'outpost_llm_calls{agent="pipeline-fixer"} 5' in metrics
    page = client.get("/admin", headers={"Authorization": "Basic " + base64.b64encode(b"ops:admin").decode()}).text
    assert "42k" in page  # 41,900 tokens for the agent and for the task row
    listed = client.get("/api/tasks", headers={"X-Admin-Token": "admin"}).json()[0]
    assert listed["prompt_tokens"] == 41000 and listed["llm_calls"] == 5
